#!/bin/sh
set -eu

psql --set ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE ROLE takura_migrator LOGIN PASSWORD '${TAKURA_MIGRATION_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  CREATE ROLE takura_runtime LOGIN PASSWORD '${TAKURA_RUNTIME_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  GRANT CONNECT ON DATABASE takura TO takura_migrator, takura_runtime;
  GRANT CREATE ON DATABASE takura TO takura_migrator;
  CREATE SCHEMA takura AUTHORIZATION takura_migrator;
  GRANT USAGE ON SCHEMA takura TO takura_runtime;
EOSQL
