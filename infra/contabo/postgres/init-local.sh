#!/bin/sh
set -eu

psql --set ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
  CREATE ROLE "${TAKURA_RUNTIME_USER}" LOGIN PASSWORD '${TAKURA_RUNTIME_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  ALTER ROLE "${POSTGRES_USER}" NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${POSTGRES_USER}", "${TAKURA_RUNTIME_USER}";
  GRANT CREATE ON DATABASE "${POSTGRES_DB}" TO "${POSTGRES_USER}";
  CREATE SCHEMA takura AUTHORIZATION "${POSTGRES_USER}";
  GRANT USAGE ON SCHEMA takura TO "${TAKURA_RUNTIME_USER}";
EOSQL
